//! Common utilities shared between CONNECT and HTTP proxy listeners.

use anyhow::Result;
use tokio::io::AsyncWriteExt;
use tokio::net::TcpStream;

pub const MAX_HEADER_BYTES: usize = 128 * 1024;

pub const MAX_HEADER_COUNT: usize = 256;

/// Marks a listener as accepting while its accept loop runs: set when the
/// socket is bound, cleared when `serve` returns or unwinds.
pub struct UpGuard(std::sync::Arc<std::sync::atomic::AtomicBool>);

impl UpGuard {
    pub fn new(up: &std::sync::Arc<std::sync::atomic::AtomicBool>) -> Self {
        up.store(true, std::sync::atomic::Ordering::Release);
        Self(up.clone())
    }
}

impl Drop for UpGuard {
    fn drop(&mut self) {
        self.0.store(false, std::sync::atomic::Ordering::Release);
    }
}

/// Turn away a client at the connection limit. HTTP-speaking listeners get a
/// best-effort `503` that names the cause; the socket is closed right away,
/// so nothing is queued.
pub fn refuse_over_limit(stream: TcpStream, listener: &'static str, replies_http: bool) {
    tracing::debug!(listener, "connection refused: connection limit reached");
    if replies_http {
        let reply = proxy_error_response(
            503,
            "Service Unavailable",
            "connection limit reached",
            &[
                (PROXY_ERROR_HEADER, "connection_limit"),
                ("Retry-After", "1"),
            ],
        );
        // One non-blocking write on the std socket: a fresh socket has an empty
        // send buffer, so it lands at once, and a full one is not worth waiting
        // for. (tokio's `try_write` would report `WouldBlock` before the
        // runtime has seen the socket become writable.)
        if let Ok(mut std_stream) = stream.into_std() {
            let _ = std::io::Write::write(&mut std_stream, &reply);
        }
    }
}

pub const PROXY_SERVER_ID: &str = "proxyx-intercept";

/// Response header naming why the socks5 listener could not set up a tunnel
/// (see `socks::report_failure`). Only ProxyX may send it: the MITM path
/// removes it from upstream responses so a target cannot fake a proxy error.
pub const PROXY_ERROR_HEADER: &str = "X-ProxyX-Error";

/// How a proxied connection ended: the `outcome` label of
/// `proxyx_intercept_connections_total`. A handler also returns `Ok` after
/// it sends the client an error reply, so `Ok` alone does not mean success.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ConnOutcome {
    /// The tunnel or forward request ran.
    Ok,
    /// Authentication, session lookup, or routing denied the client (407,
    /// in-band 503 session_not_found on socks5).
    Rejected,
    /// The session backend was unavailable or timed out (503).
    BackendUnavailable,
    /// The upstream connect failed (502).
    UpstreamError,
    /// The upstream connect hit `network.upstream_connect_timeout_ms` (504).
    UpstreamTimeout,
    /// The upstream's circuit breaker is open: the dial failed fast (503).
    UpstreamUnavailable,
}

impl ConnOutcome {
    pub fn label(self) -> &'static str {
        match self {
            ConnOutcome::Ok => "ok",
            ConnOutcome::Rejected => "rejected",
            ConnOutcome::BackendUnavailable => "backend_unavailable",
            ConnOutcome::UpstreamError => "upstream_error",
            ConnOutcome::UpstreamTimeout => "upstream_timeout",
            ConnOutcome::UpstreamUnavailable => "upstream_unavailable",
        }
    }
}

/// Escape `&`, `<`, `>`, `"` for safe embedding in HTML.
fn html_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            _ => out.push(c),
        }
    }
    out
}

/// Build a complete HTTP/1.1 error response with an HTML body that makes it
/// unambiguous the failure came from the proxy, not the destination server.
/// `detail` is a short human reason (also echoed in the X-Proxy-Error header).
/// `extra_headers` are appended verbatim (e.g. Proxy-Authenticate for 407).
pub fn proxy_error_response(
    code: u16,
    reason: &str,
    detail: &str,
    extra_headers: &[(&str, &str)],
) -> Vec<u8> {
    let header_detail: String = detail
        .chars()
        .filter(|c| *c != '\r' && *c != '\n')
        .collect();
    let body_detail = html_escape(detail);
    let body = format!(
        "<!DOCTYPE html><html><head><meta charset=\"utf-8\"><title>{code} {reason}</title></head>\
<body style=\"font-family:system-ui,sans-serif;max-width:40rem;margin:4rem auto;padding:0 1rem\">\
<h1>{code} {reason}</h1>\
<p>This response was generated by the <strong>proxyx</strong> proxy, not by the destination server.</p>\
<p><code>{body_detail}</code></p>\
<hr><p style=\"color:#888\">{PROXY_SERVER_ID}</p></body></html>"
    );
    let mut out = format!(
        "HTTP/1.1 {code} {reason}\r\n\
Server: {PROXY_SERVER_ID}\r\n\
X-Proxy-Error: {header_detail}\r\n\
Content-Type: text/html; charset=utf-8\r\n\
Content-Length: {}\r\n\
Connection: close\r\n",
        body.len()
    )
    .into_bytes();
    for (k, v) in extra_headers {
        out.extend_from_slice(format!("{k}: {v}\r\n").as_bytes());
    }
    out.extend_from_slice(b"\r\n");
    out.extend_from_slice(body.as_bytes());
    out
}

pub fn find_double_crlf(buf: &[u8]) -> Option<usize> {
    buf.windows(4)
        .position(|w| w == b"\r\n\r\n")
        .map(|idx| idx + 4)
}

pub fn has_double_crlf(buf: &[u8]) -> bool {
    find_double_crlf(buf).is_some()
}

/// Write HTTP error response with an HTML body identifying the proxy.
/// The `body` parameter is used as the human-readable detail.
pub async fn write_error_response(
    stream: &mut TcpStream,
    code: u16,
    reason: &str,
    headers: &[(&str, &str)],
    body: &str,
) -> Result<()> {
    // Filter out Connection: close — proxy_error_response adds it.
    let extra: Vec<(&str, &str)> = headers
        .iter()
        .filter(|(k, _)| !k.eq_ignore_ascii_case("Connection"))
        .copied()
        .collect();
    stream
        .write_all(&proxy_error_response(code, reason, body, &extra))
        .await?;
    Ok(())
}

/// Parse host:port from authority string, handling IPv6 brackets.
///
/// For CONNECT: "example.com:443" or "[::1]:443"
pub fn parse_host_port(authority: &str) -> Result<(String, u16)> {
    // IPv6: [::1]:443
    if let Some(rest) = authority.strip_prefix('[') {
        let end = rest
            .find(']')
            .ok_or_else(|| anyhow::anyhow!("invalid ipv6 authority: missing ]"))?;
        let host = &rest[..end];
        let port_str = rest[end + 1..]
            .strip_prefix(':')
            .ok_or_else(|| anyhow::anyhow!("missing port after IPv6 address"))?;
        let port = port_str.parse::<u16>()?;
        return Ok((host.to_ascii_lowercase(), port));
    }

    // IPv4 or hostname: example.com:443
    let mut parts = authority.rsplitn(2, ':');
    let port_str = parts
        .next()
        .ok_or_else(|| anyhow::anyhow!("missing port"))?;
    let host = parts
        .next()
        .ok_or_else(|| anyhow::anyhow!("missing host"))?;
    let port = port_str.parse::<u16>()?;
    Ok((host.to_ascii_lowercase(), port))
}

/// Parse absolute HTTP URL into (host, port, path).
///
/// For HTTP proxy: "http://example.com:80/path" -> ("example.com", 80, "/path")
pub fn parse_absolute_url(url: &str) -> Result<(String, u16, String)> {
    let url = url
        .strip_prefix("http://")
        .ok_or_else(|| anyhow::anyhow!("expected http:// URL"))?;

    let (authority, path) = match url.find('/') {
        Some(idx) => (&url[..idx], &url[idx..]),
        None => (url, "/"),
    };

    let (host, port) = if let Some(rest) = authority.strip_prefix('[') {
        // IPv6 literal: "[::1]" or "[::1]:port". Do not split on inner colons.
        let end = rest
            .find(']')
            .ok_or_else(|| anyhow::anyhow!("malformed IPv6 authority"))?;
        let host = &rest[..end];
        let port = match rest[end + 1..].strip_prefix(':') {
            Some(p) => p.parse::<u16>()?,
            None => 80,
        };
        (host.to_string(), port)
    } else if let Some(colon) = authority.rfind(':') {
        let host = &authority[..colon];
        let port = authority[colon + 1..].parse::<u16>()?;
        (host.to_string(), port)
    } else {
        (authority.to_string(), 80)
    };

    Ok((host.to_ascii_lowercase(), port, path.to_string()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_host_port() {
        assert_eq!(
            parse_host_port("example.com:443").unwrap(),
            ("example.com".to_string(), 443)
        );
        assert_eq!(
            parse_host_port("[::1]:8080").unwrap(),
            ("::1".to_string(), 8080)
        );
        assert_eq!(
            parse_host_port("localhost:80").unwrap(),
            ("localhost".to_string(), 80)
        );
    }

    #[test]
    fn test_parse_absolute_url() {
        let (host, port, path) = parse_absolute_url("http://example.com/path").unwrap();
        assert_eq!(host, "example.com");
        assert_eq!(port, 80);
        assert_eq!(path, "/path");

        let (host, port, path) = parse_absolute_url("http://example.com:8080/api/v1").unwrap();
        assert_eq!(host, "example.com");
        assert_eq!(port, 8080);
        assert_eq!(path, "/api/v1");
    }

    #[test]
    fn test_find_double_crlf() {
        assert_eq!(find_double_crlf(b"GET / HTTP/1.1\r\n\r\n"), Some(18));
        assert_eq!(find_double_crlf(b"incomplete\r\n"), None);
        assert_eq!(find_double_crlf(b"\r\n\r\n"), Some(4));
    }
}
